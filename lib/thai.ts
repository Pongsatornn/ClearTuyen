/**
 * ด่านบังคับว่า "ต้องเป็นภาษาไทยเท่านั้น" — ใช้ร่วมกันทั้ง /api/chat และ /api/transcribe
 *
 * อยู่ไฟล์เดียวกันทั้งสองที่ด้วยเหตุผลเดียวกับที่ `BIAS_PROMPT_LEAD` ถูกแยกเป็นค่าคงที่:
 * ถ้าปล่อยให้แต่ละ route เขียน regex ของตัวเอง วันที่เพิ่มภาษาที่ต้องกันเข้าไปอีกภาษา
 * จะแก้ที่เดียวแล้วลืมอีกที่ แล้วตัวกรองจะเลิกทำงานครึ่งทางโดยไม่มีอะไรฟ้อง
 *
 * ทำไมต้องบังคับฝั่งโค้ด ทั้งที่สั่งไว้ใน system prompt แล้ว: **เพราะสั่งแล้วมันยังหลุด**
 * ผู้ใช้เจอเองว่าถามยาวๆ แล้วเชฟตอบเป็นภาษาจีนมาทั้งประโยค และตอนทดสอบก็เจอคำตอบ
 * ที่ลงท้ายด้วย "？" แบบเต็มความกว้างของจีนปนมา คำสั่งใน prompt เป็นแค่การขอร้อง
 * ส่วนโค้ดตรงนี้คือการตรวจของจริงก่อนถึงหูผู้ใช้ — หลักการเดียวกับ `stripMarkdown`
 */

/**
 * สคริปต์ที่ "เจอเมื่อไหร่ = หลุดภาษาแน่นอน" ไม่ต้องตีความอะไรต่อ
 *
 * ครอบคลุมมากกว่าจีนอย่างเดียวโดยตั้งใจ เพราะโมเดลที่เริ่มเอนออกจากภาษาไทยแล้ว
 * ไม่ได้เอนไปทางจีนเสมอไป — ที่เจอในโมเดลตระกูลนี้มีทั้งญี่ปุ่น เกาหลี และเวียดนาม
 *
 * รวมช่วง Halfwidth/Fullwidth Forms (U+FF00-FFEF) ไว้ด้วย เพราะเครื่องหมายวรรคตอน
 * แบบเต็มความกว้าง (？ ！ ，) อยู่ในช่วงนี้ ไม่ได้อยู่ในช่วงตัวอักษรจีน — เป็นตัวที่
 * หลุดมาจริงตอนทดสอบและมองด้วยตาแทบแยกไม่ออกจากเครื่องหมายปกติ
 */
const FOREIGN_SCRIPT =
  /[　-〿぀-ヿ㐀-䶿一-鿿豈-﫿가-힯Ѐ-ӿ؀-ۿऀ-ॿ֐-׿＀-￯]/;

/** ตัวอักษรไทย (รวมสระ วรรณยุกต์ และเลขไทย) */
const THAI_CHAR = /[฀-๿]/g;
/** ตัวอักษรละติน — ไม่ได้ห้ามเด็ดขาด เพราะชื่อเฉพาะบางคำไม่มีคำแปลไทยจริงๆ */
const LATIN_LETTER = /[A-Za-z]/g;

/** มีตัวอักษรของภาษาที่ไม่ควรโผล่มาเลยปนอยู่ไหม */
export function hasForeignScript(text: string): boolean {
  return FOREIGN_SCRIPT.test(text);
}

/**
 * ลบตัวอักษรต่างภาษาทิ้งแล้วเก็บส่วนที่เป็นไทยไว้
 *
 * ใช้กับ **ข้อความที่ถอดเสียงมา** ไม่ใช่กับคำตอบของเชฟ — เจตนาต่างกันคนละเรื่อง:
 * คำตอบที่มีภาษาอื่นปนแปลว่าโมเดลตอบผิดภาษา ต้องให้ตอบใหม่ ส่วนข้อความถอดเสียง
 * ที่มีตัวจีนแวบเดียวปนมามักเป็นคำถามไทยจริงๆ ที่ถอดพลาดไปไม่กี่ตัว ถ้าทิ้งทั้งประโยค
 * ผู้ใช้จะต้องพูดซ้ำทั้งที่เขาพูดถูกแล้ว — ลบตัวที่เพี้ยนออกแล้วใช้ส่วนที่เหลือดีกว่า
 */
export function stripForeignScript(text: string): string {
  return text
    .replace(new RegExp(FOREIGN_SCRIPT.source, 'g'), '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

/**
 * ข้อความนี้ตอบมาเป็นภาษาไทยจริงไหม — จับเคสที่ `hasForeignScript` จับไม่ได้
 *
 * ที่ต้องมีเพิ่มเพราะการ "หลุดภาษา" ที่อันตรายที่สุดไม่ได้มาพร้อมตัวอักษรแปลกๆ เสมอไป:
 * ถ้าโมเดลตอบเป็นภาษาอังกฤษล้วนหรือเวียดนามล้วน มันใช้ตัวอักษรละตินทั้งหมด
 * ด่านตรวจสคริปต์จึงปล่อยผ่านหมด ทั้งที่ผิดกฎ "ตอบเป็นภาษาไทยเท่านั้น" เต็มๆ
 *
 * เกณฑ์คือ "ตัวอักษรไทยต้องมากกว่าตัวอักษรละติน" ไม่ใช่ "ห้ามมีละตินเลย" เพราะคำตอบ
 * ที่ถูกต้องมีชื่อเฉพาะปนได้ตามที่ system prompt อนุญาต เช่น "อุ่นที่ 80 องศา sous vide"
 * ถ้าห้ามเด็ดขาดจะตีคำตอบที่ใช้ได้จริงทิ้งเป็นว่าเล่น
 */
export function isMostlyThai(text: string): boolean {
  const thai = text.match(THAI_CHAR)?.length ?? 0;
  const latin = text.match(LATIN_LETTER)?.length ?? 0;
  if (!thai && !latin) return true; // มีแต่ตัวเลข/เครื่องหมาย — ไม่ใช่การหลุดภาษา
  return thai > latin;
}

/**
 * คำตอบนี้ผิดกฎ "ตอบเป็นภาษาไทยเท่านั้น" หรือเปล่า — ด่านเดียวที่ /api/chat เรียกใช้
 *
 * รวมสองเงื่อนไขไว้ที่เดียวเพื่อให้จุดตัดสินใจมีจุดเดียว ไม่ต้องให้ผู้เรียกจำว่า
 * ต้องเช็คทั้งสองอย่างและเช็คด้วยลำดับไหน
 */
export function violatesThaiOnly(text: string): boolean {
  return hasForeignScript(text) || !isMostlyThai(text);
}

const DIGIT_WORDS = ['ศูนย์', 'หนึ่ง', 'สอง', 'สาม', 'สี่', 'ห้า', 'หก', 'เจ็ด', 'แปด', 'เก้า'];
const PLACE_WORDS = ['', 'สิบ', 'ร้อย', 'พัน', 'หมื่น', 'แสน'];

/**
 * แปลงจำนวนเต็มเป็นคำอ่านภาษาไทยที่ถูกต้องตามหลักจริง
 *
 * มีเพราะโมเดลแปลงเองแล้วผิด และผิดแบบที่อ่านผ่านตาแล้วไม่ทันสังเกต — ของจริงที่เจอคือ
 * **"เติมน้ำเปล่าประมาณหนึ่งสิบช้อนโต๊ะ"** ซึ่ง "หนึ่งสิบ" ไม่ใช่คำไทย แต่เป็นการแปล
 * โครงสร้างเลขจีน 一十 (หนึ่ง-สิบ) มาตรงตัว — อาการเดียวกับตอนที่มันตอบเป็นภาษาจีน
 * เพียงแต่โผล่มาในรูปตัวเลข ด่าน `violatesThaiOnly` จึงจับไม่ได้เพราะตัวอักษรเป็นไทยล้วน
 *
 * ภาษาไทยมีข้อยกเว้นที่กฎตรงๆ ไม่ครอบคลุมอยู่สามข้อ ซึ่งเป็นจุดที่โมเดลพลาดบ่อยที่สุด:
 *   - 10 = "สิบ" ไม่ใช่ "หนึ่งสิบ"
 *   - 20 = "ยี่สิบ" ไม่ใช่ "สองสิบ"
 *   - เลขลงท้ายด้วย 1 ที่มีหลักอื่นนำหน้า = "เอ็ด" ไม่ใช่ "หนึ่ง" (21 = ยี่สิบเอ็ด)
 */
export function thaiNumberWords(n: number): string {
  if (!Number.isFinite(n) || n < 0) return '';
  const whole = Math.floor(n);
  if (whole === 0) return DIGIT_WORDS[0];
  // เกินหลักแสนไม่แปลง — ไม่มีปริมาณในครัวที่ใหญ่ขนาดนั้น และกฎหลัก "ล้าน" ซับซ้อนขึ้นอีกชั้น
  if (whole > 999999) return '';

  const digits = String(whole);
  let out = '';
  for (let i = 0; i < digits.length; i++) {
    const d = Number(digits[i]);
    if (d === 0) continue;
    const place = digits.length - i - 1;
    if (place === 1) {
      out += d === 1 ? 'สิบ' : d === 2 ? 'ยี่สิบ' : `${DIGIT_WORDS[d]}สิบ`;
    } else if (place === 0) {
      out += d === 1 && digits.length > 1 ? 'เอ็ด' : DIGIT_WORDS[d];
    } else {
      out += DIGIT_WORDS[d] + PLACE_WORDS[place];
    }
  }
  return out;
}

/**
 * แทนตัวเลขในข้อความด้วยคำอ่านไทย — ใช้เฉพาะตอนจะส่งให้เครื่องอ่านออกเสียง
 *
 * ไม่ได้ใช้กับข้อความที่แสดงบนจอ เพราะบนจอ "1 ถึง 2 ช้อนโต๊ะ" อ่านง่ายกว่าและกวาดตา
 * เจอเร็วกว่า "หนึ่งถึงสองช้อนโต๊ะ" — คนละสื่อคนละข้อจำกัด หลักการเดียวกับที่คำตอบ
 * สำหรับหูกับสำหรับตาใช้กฎคนละชุดใน /api/chat
 *
 * เรียงลำดับการแทนที่จากรูปที่ซับซ้อนที่สุดไปหาง่ายที่สุด (ช่วง → เศษส่วน → ทศนิยม →
 * จำนวนเต็ม) เพราะถ้าแทนจำนวนเต็มก่อน "1/2" จะกลายเป็น "หนึ่ง/สอง" ที่อ่านออกมาไม่เป็นภาษาคน
 */
/**
 * อ่านเลขหนึ่งตัวที่อาจมีทศนิยม — รวมไว้ที่เดียวเพราะทั้งกฎช่วงและกฎเลขเดี่ยวต้องใช้
 *
 * ทศนิยมอ่านทีละหลักหลังจุด ("2.5" = "สองจุดห้า" ไม่ใช่ "สองจุดห้าสิบ") ตามที่คนพูดจริง
 */
function spokenNumber(raw: string): string {
  if (!raw.includes('.')) return thaiNumberWords(Number(raw));
  const [whole, decimals] = raw.split('.');
  const wholeWords = thaiNumberWords(Number(whole));
  const decimalWords = [...decimals].map(d => DIGIT_WORDS[Number(d)]).join('');
  return wholeWords && decimalWords ? `${wholeWords}จุด${decimalWords}` : '';
}

export function speakNumbers(text: string): string {
  return (
    text
      // ครึ่ง — เขียนเป็น 1/2 บ่อยกว่า 0.5 ในสูตรอาหาร
      .replace(/(^|\D)1\/2(?=\D|$)/g, '$1ครึ่ง')
      .replace(/(\d+)\/(\d+)/g, (m, a, b) => {
        const top = thaiNumberWords(Number(a));
        const bottom = thaiNumberWords(Number(b));
        return top && bottom ? `${top}ส่วน${bottom}` : m;
      })
      /**
       * ช่วงตัวเลข "1-2" — ขีดกลางถ้าอ่านตรงตัวจะกลายเป็นเสียง "ลบ"
       *
       * ⚠️ ต้องรองรับทศนิยมทั้งสองฝั่ง (`\d+(?:\.\d+)?`) และต้องมาก่อนกฎทศนิยมเดี่ยว
       * ไม่งั้น "1.5-2.5" จะโดนคว้าเอา "5-2" ที่คร่อมจุดทศนิยมไปแปลงเป็นช่วง
       * แล้วได้ "หนึ่ง.ห้าถึงสอง.ห้า" ซึ่งอ่านออกเสียงแล้วไม่เป็นภาษาคนเลย
       */
      .replace(/(\d+(?:\.\d+)?)\s*[-–]\s*(\d+(?:\.\d+)?)/g, (m, a, b) => {
        const from = spokenNumber(a);
        const to = spokenNumber(b);
        return from && to ? `${from}ถึง${to}` : m;
      })
      // ทศนิยมที่เหลือ (ตัวที่ไม่ได้อยู่ในช่วง) แล้วค่อยถึงจำนวนเต็มล้วน
      .replace(/\d+(?:\.\d+)?/g, m => spokenNumber(m) || m)
  );
}

/**
 * ซ่อมคำอ่านตัวเลขที่โมเดลสะกดผิดหลักภาษาไทยมาเอง
 *
 * ถึงจะสั่งให้เขียนเป็นตัวเลขแล้ว (เพื่อให้ `speakNumbers` แปลงให้) แต่โมเดลยังเขียน
 * เป็นคำมาเองได้อยู่ดี ตัวนี้จึงเป็นตาข่ายรองรับ และใช้กับข้อความที่ขึ้นจอด้วย
 * ไม่ใช่แค่ตอนอ่านออกเสียง เพราะ "หนึ่งสิบ" บนจอก็ยังผิดอยู่ดี
 */
export function fixThaiNumerals(text: string): string {
  return text
    .replace(/หนึ่งสิบ/g, 'สิบ')
    .replace(/สองสิบ/g, 'ยี่สิบ')
    // 11, 21, 31... ลงท้ายด้วย "หนึ่ง" ต้องเป็น "เอ็ด" — ไม่มี lookahead เพราะคำที่ตาม
    // หลังมักเป็นหน่วย ("สิบหนึ่งเม็ด") ซึ่งเป็นเคสที่ต้องซ่อม ไม่ใช่เคสที่ต้องเว้น
    .replace(/สิบหนึ่ง/g, 'สิบเอ็ด');
}
