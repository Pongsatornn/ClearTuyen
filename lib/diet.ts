function getPreset(id: string): DietPreset | undefined {
  return DIET_PRESETS.find(p => p.id === id);
}

// ตัดช่องว่างและตัวพิมพ์เล็กใหญ่ทิ้งก่อนเทียบ เพราะ AI เขียน "น้ำ ปลา" บ้าง "น้ำปลา" บ้าง
function normalize(text: string): string {
  return text.toLowerCase().replace(/\s+/g, '');
}

export interface DietViolation {
  // เงื่อนไขที่ถูกละเมิด (เอาไปขึ้นข้อความให้ผู้ใช้อ่านได้เลย)
  restriction: string;
  // คำที่ไปตรงกับของต้องห้าม
  matched: string;
}

// ตรวจข้อความหนึ่งก้อน (ชื่อเมนู หรือชื่อวัตถุดิบ) ว่าขัดกับเงื่อนไขที่เลือกไว้ไหม
// คืนทุกข้อที่ขัด ไม่ใช่แค่ข้อแรก เพื่อให้ข้อความเตือนบอกได้ครบว่าผิดกฎอะไรบ้าง
export function findDietViolations(
  text: string,
  restrictionIds: string[],
  allergies: string[] = []
): DietViolation[] {
  const target = normalize(text);
  if (!target) return [];

  const violations: DietViolation[] = [];

  for (const id of restrictionIds) {
    const preset = getPreset(id);
    if (!preset) continue;

    // ลบคำยกเว้นออกจากข้อความก่อน แล้วค่อยหาคำต้องห้ามในส่วนที่เหลือ
    // (ไม่งั้น "ไข่ไก่" จะโดนจับว่าเป็น "ไก่" ทั้งที่มังสวิรัติกินไข่ได้)
    let scan = target;
    for (const allowed of preset.allow) {
      scan = scan.split(normalize(allowed)).join('');
    }

    const matched = preset.banned.find(word => scan.includes(normalize(word)));
    if (matched) violations.push({ restriction: preset.shortLabel, matched });
  }

  // ของที่ผู้ใช้พิมพ์เองว่าแพ้ — เทียบตรงๆ ไม่มีลิสต์ยกเว้น เพราะเราไม่รู้บริบทของคำที่เขาพิมพ์มา
  for (const allergy of allergies) {
    const word = normalize(allergy);
    if (word && target.includes(word)) {
      violations.push({ restriction: `แพ้${allergy}`, matched: allergy });
    }
  }

  return violations;
}

// รวมกฎทั้งหมดเป็นข้อความก้อนเดียวสำหรับฝังใน prompt
// คืนค่าว่างเมื่อไม่มีเงื่อนไขอะไรเลย เพื่อให้ prompt เดิมไม่มีบรรทัดว่างงอกมา
export function buildDietPromptRules(restrictionIds: string[], allergies: string[] = []): string {
  const lines: string[] = [];

  for (const id of restrictionIds) {
    const preset = getPreset(id);
    if (preset) lines.push(`- ${preset.shortLabel}: ${preset.rule}`);
  }

  if (allergies.length > 0) {
    lines.push(
      `- ผู้ใช้แพ้อาหารต่อไปนี้: ${allergies.join(', ')} — ห้ามใช้ของพวกนี้และของที่มีส่วนผสมของมันเด็ดขาด ห้ามแนะนำให้ใช้แม้แต่ปริมาณเล็กน้อย`
    );
  }

  if (lines.length === 0) return '';

  return `ข้อจำกัดด้านอาหารของผู้ใช้ (สำคัญที่สุด สำคัญกว่ากฎอื่นทุกข้อ ถ้าขัดกับกฎอื่นให้ยึดข้อนี้):
${lines.join('\n')}
ถ้าวัตถุดิบที่ผู้ใช้มีไม่พอจะทำเมนูที่ตรงตามข้อจำกัดข้างต้นได้เลย ให้ตอบ { "error": "..." } อธิบายเป็นภาษาไทย ห้ามฝืนแต่งเมนูที่ผิดข้อจำกัดออกมาเด็ดขาด`;
}

// อ่านค่าที่ client ส่งมาให้ปลอดภัยก่อนใช้ (ทั้งสอง API route ใช้ตัวนี้ร่วมกัน)
// เงื่อนไข: รับเฉพาะ id ที่มีจริง / ของแพ้: ตัดอักขระที่ใช้แทรกคำสั่งใน prompt ทิ้ง จำกัดความยาวและจำนวน
export function sanitizeDietInput(rawRestrictions: unknown, rawAllergies: unknown) {
  const restrictions = Array.isArray(rawRestrictions)
    ? rawRestrictions.filter((id): id is string => typeof id === 'string' && !!getPreset(id))
    : [];

  const allergies = Array.isArray(rawAllergies)
    ? rawAllergies
        .filter((a): a is string => typeof a === 'string')
        .map(a => a.replace(/[<>{}[\]"'\\\n\r]/g, '').trim().slice(0, 30))
        .filter(Boolean)
        .slice(0, 10)
    : [];

  return { restrictions, allergies };
}
