export const MAX_AUDIO_BYTES = 4 * 1024 * 1024;

/**
 * นามสกุลไฟล์ที่ Groq ใช้เดาชนิดเสียง — ต้องตั้งให้ตรง ไม่งั้นโดนปฏิเสธทั้งคลิป
 *
 * จำเป็นเพราะ MediaRecorder แต่ละเบราว์เซอร์อัดออกมาคนละชนิด:
 * Chrome/Firefox ได้ `audio/webm;codecs=opus` ส่วน Safari บน iOS ได้ `audio/mp4`
 * ซึ่งเป็นเบราว์เซอร์ที่คนใช้ยืนทำอาหารเยอะที่สุด จะปล่อยให้พังไม่ได้
 */
export function audioExtensionFor(mimeType: string): string {
  const type = mimeType.split(';')[0].trim().toLowerCase();
  switch (type) {
    case 'audio/webm':
    case 'video/webm':
      return 'webm';
    case 'audio/mp4':
    case 'video/mp4':
    case 'audio/x-m4a':
      return 'm4a';
    case 'audio/mpeg':
      return 'mp3';
    case 'audio/ogg':
      return 'ogg';
    case 'audio/wav':
    case 'audio/wave':
    case 'audio/x-wav':
      return 'wav';
    case 'audio/flac':
      return 'flac';
    default:
      // เดาเป็น webm ไว้ก่อน — เป็นชนิดที่เบราว์เซอร์ส่วนใหญ่อัดออกมา
      // และ Groq รับอยู่แล้ว ดีกว่าปฏิเสธทั้งคลิปเพราะชื่อชนิดแปลกไปนิดเดียว
      return 'webm';
  }
}

/**
 * เตรียมข้อความก่อนให้เครื่องอ่านออกเสียง
 *
 * `/api/chat` กรอง Markdown ออกให้แล้ว (ดู stripMarkdown ที่นั่น) แต่ยังเหลือของที่
 * "อ่านบนจอแล้วเข้าใจ แต่ฟังแล้วสะดุด" อีกชุด — อีโมจิที่ถูกอ่านเป็นชื่อเต็มของมัน,
 * เลขข้อขึ้นต้นบรรทัดที่กลายเป็นเสียงพึมพำ, และบรรทัดว่างที่ทำให้เสียงขาดหายเป็นช่วง
 *
 * รวมถึงการแปลงตัวเลขเป็นคำอ่านไทยด้วย (`speakNumbers`) ซึ่งย้ายมาทำตรงนี้แทนที่จะ
 * สั่งให้โมเดลเขียนเป็นคำมาเอง — โมเดลแปลงเองแล้วพลาด เคยได้ "หนึ่งสิบช้อนโต๊ะ"
 * (แปลโครงสร้างเลขจีน 一十 มาตรงตัว) ส่วนโค้ดแปลงถูกทุกครั้งเพราะเป็นกฎตายตัว
 * ทำที่นี่ยังได้ผลพลอยได้: ข้อความบนจอยังเป็นตัวเลขที่กวาดตาอ่านง่าย ส่วนหูได้คำอ่านเต็ม
 */
export function toSpeakableText(text: string): string {
  return speakNumbers(text)
    // อีโมจิ/สัญลักษณ์ — เครื่องอ่านไทยอ่านออกมาเป็นชื่อยาวๆ กลางประโยค
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/gu, '')
    // "1." "2)" ขึ้นต้นบรรทัด — บนจอคือหัวข้อ แต่ฟังแล้วเป็นตัวเลขลอยไม่มีที่มา
    .replace(/^\s*\d+[.)]\s*/gm, '')
    // ยุบบรรทัดว่างซ้อน แล้วต่อบรรทัดด้วยการเว้นวรรคให้เสียงลื่นเป็นประโยคเดียว
    .replace(/\n{2,}/g, '\n')
    .replace(/\n/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

/**
 * ขอบเขตท้ายประโยคของข้อความที่เชฟตอบ
 *
 * ภาษาไทยไม่ใช้จุดจบประโยค การนับ "กี่ประโยค" จึงต้องอาศัยสองอย่างรวมกัน:
 * เครื่องหมายจบประโยคแบบฝรั่ง/จีนที่โมเดลใส่มาบ้าง กับคำลงท้ายสุภาพไทย
 * (ครับ/ค่ะ/นะครับ/นะคะ) ซึ่งเชฟลงท้ายแทบทุกประโยคอยู่แล้วตามบุคลิกที่สั่งไว้
 */
const SENTENCE_END = /(?<=[.!?。！？])\s+|(?<=ครับ|ค่ะ|นะคะ|นะครับ)\s+/;

/**
 * คำเชื่อมที่ห้ามค้างอยู่ท้ายข้อความหลังถูกตัด
 *
 * ตัดไม่กลางคำอย่างเดียวยังไม่พอ — จุดตัดที่ตกลงหลังคำเชื่อมพอดีจะได้ประโยคอย่าง
 * "ผัดที่สองร้อยองศา นานสามถึง" ซึ่งทุกคำสมบูรณ์แต่ฟังแล้วยังเหมือนเชฟพูดค้างอยู่ดี
 * เพราะคำเชื่อมประกาศว่ายังมีของตามมา แล้วมันไม่มา
 *
 * เรียงจากยาวไปสั้นเพราะต้องตัด "แล้วก็" ก่อน "ก็" ไม่งั้นจะเหลือ "แล้ว" ค้างไว้แทน
 */
const DANGLING_WORDS = [
  'จากนั้น',
  'ประมาณ',
  'แล้วก็',
  'เพื่อ',
  'ราว',
  'สัก',
  'ถึง',
  'และ',
  'แล้ว',
  'หรือ',
  'กับ',
  'แต่',
  'จน',
  'ของ',
  'ที่',
  'ใน',
  'ก็',
];

/**
 * เก็บกวาดหางที่ค้างหลังตัด — คำเชื่อมลอย และตัวเลขที่ไม่มีหน่วยตามหลัง
 *
 * ตัวเลขโดดท้ายข้อความเป็นร่องรอยของการตัดเกือบทุกครั้ง เพราะคำตอบเรื่องอาหารที่จบจริง
 * ลงท้ายด้วยหน่วยหรือคำสุภาพเสมอ ไม่มีใครพูดจบด้วยตัวเลขเปล่าๆ ("ใส่น้ำปลา 2")
 * ปล่อยไว้จะได้เสียง "ใส่น้ำปลา สอง" ที่ค้างคาหนักกว่าการตัดคำนั้นทิ้งไปเลย
 */
function trimDanglingTail(text: string): string {
  let out = text.trim();
  for (let changed = true; changed; ) {
    changed = false;
    // ตัวเลขลอยท้ายข้อความ และขีดกลางที่ค้างจากช่วงตัวเลขที่ถูกตัดครึ่ง
    //
    // ต้องรับขีดกลางด้วย ไม่ใช่แค่ตัวเลข ไม่งั้นตัวลูปนี้จะ**สร้างปัญหาขึ้นมาเอง**:
    // "ประมาณ 2-3" โดนตัด "3" ทิ้งแล้วเหลือ "ประมาณ 2-" ซึ่งไม่เข้าเงื่อนไขไหนอีกเลย
    // ลูปจึงหยุดโดยทิ้งขีดกลางค้างไว้ท้ายประโยค (เจอจริงตอนทดสอบบนเว็บ)
    const withoutNumber = out.replace(/[\s,]*(\d+(?:\.\d+)?|[-–])$/, '').trim();
    if (withoutNumber !== out && withoutNumber) {
      out = withoutNumber;
      changed = true;
    }
    for (const word of DANGLING_WORDS) {
      if (out.endsWith(word)) {
        const rest = out.slice(0, -word.length).trim();
        // อย่าตัดจนไม่เหลืออะไร — คำเชื่อมที่เป็นทั้งข้อความแปลว่าตัดมาผิดตั้งแต่ต้นแล้ว
        if (!rest) break;
        out = rest;
        changed = true;
        break;
      }
    }
  }
  return out;
}

/** ตัดข้อความเป็นประโยค — ใช้ร่วมกันระหว่างการแบ่งท่อนอ่านออกเสียงกับการจำกัดความยาว */
export function splitSentences(text: string): string[] {
  return text.split(SENTENCE_END).filter(Boolean);
}

/**
 * ตัดคำตอบให้สั้นพอที่คนฟังรับไหว — ด่านสุดท้ายก่อนคำตอบถูกอ่านออกเสียงในโหมดโทรคุย
 *
 * `/api/chat` สั่งไว้ใน system prompt แล้วว่าโหมดเสียงห้ามเกินสองประโยค แต่เชื่อคำสั่ง
 * อย่างเดียวไม่พอ ด้วยหลักการเดียวกับที่ route นั้นต้องมี `stripMarkdown` ทั้งที่สั่งห้าม
 * Markdown ไปแล้ว: สั่ง AI อย่างเดียวไม่พอ ต้องตรวจผลลัพธ์ก่อนถึงหู/จอด้วย
 *
 * ทำไมต้องบังคับตรงนี้ ไม่ใช่แค่ขอร้องใน prompt: คำตอบยาวเกินในโหมดเสียงไม่ได้แค่
 * "อ่านเยอะไปหน่อย" แต่มันกินเวลาจริงเป็นสิบวินาทีที่ไมค์ถูกปิดอยู่ ผู้ใช้ที่อยากถามต่อ
 * ต้องยืนรอฟังจนจบหรือเอามือเปื้อนไปกดปุ่มพูดแทรก — เสียหายกว่าการถูกตัดท้ายประโยคทิ้ง
 *
 * เพดานตัวอักษรตั้งไว้กว้างกว่าสองประโยคปกติ (ประโยคพูดไทยราว 60-90 ตัวอักษร)
 * เพื่อให้มันเป็นแค่กันเหนียวของกรณีที่โมเดลเขียนรวดเดียวไม่ลงท้ายสักที
 * ไม่ใช่กรรไกรที่ตัดคำตอบปกติทุกอัน
 */
export function limitSpokenReply(text: string, maxSentences = 2, maxChars = 200): string {
  const clean = text.trim();
  if (!clean) return clean;

  // ถ้าแบ่งประโยคไม่ออกเลย (ไม่มีทั้งเครื่องหมายและคำลงท้าย) ให้ถือทั้งก้อนเป็นประโยคเดียว
  // แล้วไปวัดกันต่อที่เพดานตัวอักษรข้างล่าง ดีกว่าคืนสตริงว่างให้เชฟเงียบไปทั้งรอบ
  const kept = splitSentences(clean).slice(0, maxSentences).join(' ').trim() || clean;

  /**
   * วัดความยาวจาก "ตอนพูด" ไม่ใช่ "ตอนเขียน" — ตัวเลขพองขึ้นมากเมื่อกลายเป็นคำอ่าน
   *
   * "150 กรัม" เขียนแค่ 8 ตัวอักษร แต่พูดออกมาเป็น "หนึ่งร้อยห้าสิบกรัม" ยาว 18 ตัว
   * ถ้านับจากข้อความที่เขียน คำตอบที่มีตัวเลขเยอะจะพูดยาวเกือบเท่าตัวของเพดานที่ตั้งไว้
   * ซึ่งผิดเจตนาของเพดานนี้ทั้งหมด เพราะมันมีไว้คุม**เวลาที่คนต้องยืนฟัง** ไม่ใช่คุม
   * จำนวนตัวอักษรบนจอ
   *
   * ย่อเพดานตามสัดส่วนที่พองขึ้นแทนการหาตำแหน่งตัดในข้อความที่แปลงแล้ว เพราะตำแหน่ง
   * ตัวอักษรของสองรูปแบบไม่ตรงกัน การแมปกลับไปมาจะเปราะกว่าและพังเงียบเมื่อรูปแบบเปลี่ยน
   */
  const spokenLength = speakNumbers(kept).length;
  if (spokenLength <= maxChars) return kept;

  const budget = Math.max(1, Math.floor(kept.length * (maxChars / spokenLength)));
  const head = kept.slice(0, budget);
  /** ต่ำกว่านี้ถือว่าตัดแล้วเหลือน้อยเกินจนไม่เป็นคำตอบ ยอมปล่อยยาวดีกว่า */
  const floor = budget / 3;

  // 1) จุดตัดที่ดีที่สุดคือคำลงท้ายสุภาพ — เป็นที่จบประโยคจริงในภาษาพูด
  for (const ending of ['ครับ', 'ค่ะ']) {
    const at = head.lastIndexOf(ending);
    if (at > floor) return head.slice(0, at + ending.length).trim();
  }

  /**
   * 2) ไม่มีคำลงท้ายก็ตัดที่เว้นวรรค — **ภาษาไทยใช้เว้นวรรคคั่นประโยคและอนุประโยค**
   *    ไม่ได้ใช้คั่นระหว่างคำแบบภาษาอังกฤษ ช่องว่างที่เจอจึงเป็นรอยต่อของใจความ
   *    ไม่ใช่กลางคำ ("...ระเหยเร็ว | ควรเพิ่มไฟแรง...")
   */
  const lastSpace = head.lastIndexOf(' ');
  if (lastSpace > floor) return trimDanglingTail(head.slice(0, lastSpace));

  /**
   * 3) หาจุดตัดที่สะอาดไม่เจอเลย = **ไม่ตัด** ไม่ใช่ฟันตรงเพดาน
   *
   * เดิมโค้ดตรงนี้ยอมฟันตรงตัวอักษรสุดท้ายที่นับได้ ซึ่งผิดถนัดกับภาษาไทยที่เขียน
   * ติดกันไม่มีช่องว่างระหว่างคำ — ผลคือฟันกลางคำ ได้คำตอบที่จบด้วย "หอมไม่ต้"
   * หรือ "ไม่แห้งเกิน" พออ่านออกเสียงจะเหมือนเชฟพูดค้างกลางคำแล้วเงียบไปเฉยๆ
   *
   * คำตอบที่ยาวเกินไปแต่**พูดจบคำ** ดีกว่าคำตอบสั้นที่ขาดกลางคำเสมอ — ความยาว
   * แค่น่ารำคาญ ส่วนคำที่ขาดครึ่งคือข้อมูลที่ผู้ใช้เอาไปทำตามไม่ได้เลย
   */
  return kept;
}

/**
 * ตัดข้อความยาวเป็นท่อนสั้นก่อนส่งเข้า speechSynthesis
 *
 * ไม่ใช่เรื่องความสวยงาม แต่เป็นการเลี่ยงบั๊กจริงของ Chrome: utterance ที่ยาวเกิน
 * ประมาณ 15 วินาทีจะถูกตัดจบกลางคันเงียบๆ โดยไม่มี error ให้จับ — คนยืนหน้าเตา
 * จะได้ยินคำแนะนำหายไปครึ่งประโยคแล้วไม่รู้ว่าตัวเองพลาดอะไรไป
 *
 * ตัดที่ท้ายประโยคก่อน ถ้าท่อนไหนยังยาวเกินค่อยตัดที่ช่องว่าง — ไม่ตัดกลางคำ
 * เพราะเสียงจะสะดุดจนฟังไม่ออกว่าเป็นคำอะไร
 */
export function chunkForSpeech(text: string, maxChars = 180): string[] {
  const clean = toSpeakableText(text);
  if (!clean) return [];

  const sentences = splitSentences(clean);
  const chunks: string[] = [];
  let current = '';

  for (const sentence of sentences) {
    if (current && (current + ' ' + sentence).length > maxChars) {
      chunks.push(current);
      current = sentence;
    } else {
      current = current ? `${current} ${sentence}` : sentence;
    }
  }
  if (current) chunks.push(current);

  // ประโยคเดียวที่ยาวเกินเพดานเอง (ภาษาไทยไม่มีจุดจบประโยค เจอบ่อย) — ตัดที่ช่องว่าง
  return chunks.flatMap(chunk => {
    if (chunk.length <= maxChars) return [chunk];
    const parts: string[] = [];
    let buffer = '';
    for (const word of chunk.split(' ')) {
      if (buffer && (buffer + ' ' + word).length > maxChars) {
        parts.push(buffer);
        buffer = word;
      } else {
        buffer = buffer ? `${buffer} ${word}` : word;
      }
    }
    if (buffer) parts.push(buffer);
    return parts;
  });
}
