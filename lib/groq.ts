/**
 * สร้าง Groq client ที่ตั้งค่า retry ไว้แล้ว — ทุก route ต้องใช้ตัวนี้ ห้าม `new Groq()` เอง
 *
 * มีอยู่เพราะ **เพดาน 8,000 token ต่อนาที (TPM) ของ free tier คือของที่ทุก route แชร์กัน**
 * ไม่ใช่โควตาของใครของมัน คำขอสูตรหนึ่งครั้งกินราว 3,000 token แปลว่าสองคำขอในนาทีเดียว
 * ก็เกือบเต็มแล้ว คำขอที่สามจะได้ HTTP 429 กลับมา
 *
 * SDK retry ให้อยู่แล้วโดยเคารพ header `retry-after` ที่ Groq ส่งมา (วัดจริงได้ 1-9 วินาที)
 * แต่ค่าเริ่มต้นคือ 2 ครั้งซึ่งน้อยไปตอนโควตาตัน — จาก log ของ production พบว่าคำขอ
 * ที่ retry ครบแล้วยังชนอยู่คิดเป็น 4 ใน 18 ครั้ง (~22%) ผู้ใช้เห็นเป็น "เกิดข้อผิดพลาด"
 *
 * ⚠️ ขยับ maxRetries ขึ้นมากกว่านี้ไม่ได้ เพราะแต่ละครั้งต้องรอตาม retry-after จริงๆ
 * ถ้ารอรวมกันนานเกิน maxDuration ของ Vercel function จะถูกตัดกลางคันแทน ซึ่งแย่กว่าเดิม
 * เพราะผู้ใช้รอนานแล้วยังไม่ได้อะไร
 */
export function createGroqClient(): Groq {
  return new Groq({ apiKey: process.env.GROQ_API_KEY, maxRetries: 4 });
}

/**
 * คำขอนี้ล้มเพราะชนโควตาของ Groq หรือเปล่า (ไม่ใช่เพราะโค้ดหรือโมเดลพัง)
 *
 * ต้องแยกให้ออกจาก error อื่น เพราะสิ่งที่ผู้ใช้ควรทำต่างกันคนละเรื่อง: ชนโควตาแปลว่า
 * "รอสักครู่แล้วกดใหม่ได้เลย ของที่พิมพ์ไว้ไม่ผิดอะไร" ส่วน error อื่นแปลว่ามีอะไรผิดจริง
 * ข้อความเดียวกันสำหรับสองกรณีนี้ทำให้ผู้ใช้เดาไม่ถูกว่าควรลองใหม่หรือควรแก้ที่ตัวเอง
 */
export function isRateLimited(error: unknown): boolean {
  return typeof error === 'object' && error !== null && (error as { status?: number }).status === 429;
}

