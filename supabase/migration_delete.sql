-- ============================================================
-- กรณีที่ 1: ยังไม่ได้รัน migration_auth.sql (ยังใช้ mock auth อยู่)
-- ============================================================
-- policy ชุดปัจจุบันเป็นของ role anon และ user_id เป็น text ที่ตรวจสอบไม่ได้
-- จึงให้สิทธิ์ลบแบบเดียวกับที่ให้สิทธิ์อ่าน/เขียนอยู่แล้ว (using (true))
--
-- ⚠️ นี่ไม่ปลอดภัยในเชิงระบบ — ใครมี anon key (ซึ่งฝังอยู่ใน JS bundle) ก็ลบเมนูของคนอื่นได้
--    แต่ก็ไม่ได้แย่ลงกว่าสถานะปัจจุบันที่เขาอ่านและเขียนทับได้อยู่แล้ว
--    ถ้าจะเอาขึ้นใช้จริงกับคนหลายคน ต้องไปทำกรณีที่ 2 ไม่ใช่อยู่กับกรณีที่ 1
create policy "anon can delete recipes"
  on public.saved_recipes
  for delete
  to anon
  using (true);

