/**
 * คำขึ้นต้นของคำใบ้ที่ส่งให้ Whisper — แยกเป็นค่าคงที่เพราะมีอีกที่หนึ่งที่ต้องรู้จักมัน
 * (`echoesBiasPrompt` ข้างล่าง) ถ้าปล่อยให้เขียนซ้ำสองที่ วันที่แก้ข้อความคำใบ้
 * ตัวกรองจะเลิกทำงานเงียบๆ โดยไม่มีอะไรฟ้อง
 */
const BIAS_PROMPT_LEAD = 'นี่คือคำถามระหว่างทำอาหารในครัว เกี่ยวกับ';

/**
 * สร้าง "คำใบ้" ให้ Whisper รู้ล่วงหน้าว่ากำลังจะได้ยินศัพท์อะไรบ้าง
 *
 * นี่คือส่วนที่ทำให้การถอดเสียงไทยในแอปนี้แม่นขึ้นแบบเห็นได้ชัด และเป็นเหตุผลหลัก
 * ที่เลือกยิง Whisper แทนการใช้ SpeechRecognition ของเบราว์เซอร์ (ซึ่งใส่คำใบ้ไม่ได้เลย)
 *
 * Whisper รับ `prompt` เป็นบริบทของเสียงที่กำลังจะมา แล้วเอนไปทางคำในนั้นเวลาเจอเสียง
 * ที่ตีความได้หลายทาง — ปัญหาที่เกิดจริงกับศัพท์ครัวไทยที่เสียงใกล้กันมาก เช่น
 * "กะเพรา" กับ "กะเพา"/"กระเพรา", "ตะไคร้" กับ "ตะไกร", "ข่า" กับ "ขา"
 * พอบอกไปก่อนว่าในครัวนี้มีกะเพราและตะไคร้อยู่จริง มันจะเลือกคำที่ถูกให้เอง
 *
 * ⚠️ ช่องนี้รับได้ประมาณ 224 token เท่านั้น ส่วนที่เกินถูกตัดทิ้งเงียบๆ จึงต้องตัดเอง
 * ให้สั้นก่อน และเรียงของที่สำคัญที่สุด (ชื่อเมนู แล้วค่อยวัตถุดิบ) ไว้ต้นสุด
 */
function buildBiasPrompt(recipeName?: string, terms?: string[]): string | undefined {
  const parts: string[] = [];
  if (recipeName) parts.push(recipeName);

  const seen = new Set<string>();
  for (const term of terms ?? []) {
    if (typeof term !== 'string') continue;
    // ตัดปริมาณ/หน่วยออก เหลือแต่ชื่อของ — "หมูสับ 200 กรัม" ไม่ได้ช่วยให้ถอดคำว่า
    // "หมูสับ" แม่นขึ้น แต่กินโควตา token ที่มีน้อยอยู่แล้วไปฟรีๆ
    const name = term.replace(/[\d/.-]+\s*\S*$/u, '').trim() || term.trim();
    const key = name.toLowerCase();
    if (!name || seen.has(key)) continue;
    seen.add(key);
    parts.push(name);
  }

  if (!parts.length) return undefined;

  // ประกอบเป็นประโยคไทยธรรมดา ไม่ใช่ลิสต์คั่นด้วยจุลภาคล้วน เพราะ prompt ของ Whisper
  // ทำงานเหมือน "ข้อความก่อนหน้าในบทสนทนาเดียวกัน" — เขียนให้เป็นภาษาที่มันคุ้น
  // ยังช่วยล็อกภาษาที่จะถอดออกมาให้เป็นไทยไปในตัวด้วย
  // ⚠️ ตัดเหลือ 16 คำ ไม่ใช่ 40 — คำใบ้ที่ยาวเกินไป "ชี้นำ" จนเสียมากกว่าได้
  //
  // Whisper ไม่ได้อ่านคำใบ้เป็นแค่รายการศัพท์ที่ควรรู้จัก แต่อ่านเป็นข้อความก่อนหน้าที่
  // มันควรเขียนต่อ ยิ่งอัดชื่อวัตถุดิบเข้าไปเยอะ มันยิ่งเชื่อว่าประโยคถัดไปต้องมีคำพวกนี้
  // แล้วดึงคำจากลิสต์มาแทนคำที่ผู้ใช้พูดจริงเวลาเสียงกำกวม ซึ่งกลายเป็นสาเหตุของอาการ
  // "คำที่พูดกับคำที่ถอดออกมาไม่ตรงกัน" แทนที่จะเป็นตัวช่วย
  //
  // 16 คำครอบคลุมชื่อเมนูกับวัตถุดิบหลักที่ผู้ใช้พูดถึงจริงเกือบทั้งหมดอยู่แล้ว
  // ส่วนที่ตัดออกคือของท้ายลิสต์ที่แทบไม่มีใครถามถึง แต่กินน้ำหนักการชี้นำเท่ากัน
  const list = parts.slice(0, 16).join(' ');
  return `${BIAS_PROMPT_LEAD} ${list}`.slice(0, 800);
}

/**
 * ข้อความที่ถอดออกมาเป็นแค่คำใบ้ของเราเองที่สะท้อนกลับมา ไม่ใช่เสียงของผู้ใช้
 *
 * Whisper รับ `prompt` เข้าไปเหมือน "ข้อความก่อนหน้าในบทสนทนาเดียวกัน" ซึ่งเป็นเหตุผล
 * ที่มันช่วยเรื่องศัพท์ครัวไทยได้ดี แต่ก็มีผลข้างเคียงที่ตามมาด้วย: **พอคลิปไหนไม่มี
 * เสียงพูดจริงให้ถอด มันมักคายคำใบ้นั้นออกมาเป็นคำตอบแทน** เพราะเป็นข้อความเดียว
 * ที่มันมีอยู่ในมือ
 *
 * ในโหมดโทรคุยเรื่องนี้ไม่ใช่แค่ข้อความเพี้ยนบรรทัดเดียว — ข้อความที่คายออกมาจะถูกส่ง
 * ต่อไปให้เชฟเป็น "คำถามของผู้ใช้" ทันที และเชฟที่ได้รับประโยคว่า "นี่คือคำถามระหว่าง
 * ทำอาหารในครัว เกี่ยวกับ ผัดกะเพราหมูสับ ใบกะเพรา..." ก็จะร่ายสูตรทั้งเมนูออกมายาวเหยียด
 * ทั้งที่ผู้ใช้ไม่ได้ถามอะไรเลยสักคำ (แค่วางกระทะเสียงดังไปที)
 *
 * เกณฑ์ความดังใน `useVoiceCall` กันเสียงพวกนี้ได้เกือบหมดแล้ว แต่เสียงกระแทกดังๆ
 * ผ่านด่านนั้นได้ ตรงนี้จึงเป็นด่านที่สอง — และถูกกว่าด่านแรกมาก เพราะรู้ผลแล้วว่า
 * ข้อความที่ได้ไม่ใช่ของผู้ใช้แน่ๆ ไม่ต้องเดา
 */
function echoesBiasPrompt(text: string, biasPrompt?: string): boolean {
  if (!biasPrompt) return false;
  const normalized = text.replace(/\s+/g, ' ').trim();
  if (normalized.startsWith(BIAS_PROMPT_LEAD)) return true;
  // บางครั้งมันคายเฉพาะท่อนกลางของคำใบ้ (ลิสต์วัตถุดิบล้วนๆ ไม่มีคำขึ้นต้น) ออกมา
  // แต่ต้องยาวพอสมควรถึงจะฟันธงได้ ไม่งั้นคนที่พูดสั้นๆ ว่า "กะเพรา" คำเดียว
  // ซึ่งเป็นคำที่อยู่ในคำใบ้พอดี จะโดนกรองทิ้งไปด้วยทั้งที่เป็นเสียงของเขาจริงๆ
  return normalized.length >= 20 && biasPrompt.includes(normalized);
}

/**
 * ตัวเลขคุณภาพที่ Whisper แนบมาให้แต่ละท่อนเมื่อขอผลแบบ `verbose_json`
 *
 * ประกาศเองเพราะ groq-sdk ระบุชนิดของผลลัพธ์ไว้แค่ `{ text: string }` ช่องเดียว
 * (ดู node_modules/groq-sdk/resources/audio/transcriptions.d.ts) ทั้งที่ตอนขอแบบ
 * verbose_json มันคืนมามากกว่านั้นจริงๆ ทุกช่องจึงเป็น optional และต้องเช็คก่อนใช้เสมอ
 */
interface WhisperSegment {
  no_speech_prob?: number;
  avg_logprob?: number;
  compression_ratio?: number;
}

/**
 * Whisper แต่งประโยคขึ้นมาเองจากคลิปที่ไม่มีคนพูด — ตัวชี้วัดที่ตัวมันเองบอกเรา
 *
 * **นี่คือปัญหาที่ต้องแก้ ไม่ใช่การเผื่อไว้เฉยๆ** ทดสอบกับเว็บจริงด้วยคลิปสามแบบที่
 * ไม่มีเสียงพูดสักคำ (เงียบสนิท / เสียงพัดลม / เสียงของกระแทกหนึ่งที) แล้วได้ข้อความ
 * ภาษาไทยกลับมาทั้งสามอัน เช่น "กลับไปที่นี่" ซึ่งไม่มีอยู่ในเสียงเลย — และในโหมดโทรคุย
 * ประโยคที่แต่งขึ้นนั้นจะถูกส่งต่อไปให้เชฟตอบทันทีเหมือนเป็นคำถามจริงของผู้ใช้
 *
 * Whisper รู้ตัวว่ากำลังเดา และบอกออกมาเป็นตัวเลข เราแค่ต้องขอดู แต่ **ตัวที่ใช้ได้จริง
 * ไม่ใช่ตัวที่ชื่อตรงที่สุด** — วัดจากคลิปทดสอบสามอันข้างต้นบนเว็บจริงได้ตามนี้:
 *
 * | คลิป          | ข้อความที่แต่งขึ้น          | avg_logprob | no_speech_prob | compression |
 * |---------------|-----------------------------|-------------|----------------|-------------|
 * | เงียบสนิท      | "ก็คือ ในตัวตัว แม่งของเรา..." | -0.727      | 0.051          | 2.067       |
 * | เสียงพัดลม     | "ก็คือ แบบนี้"                | -0.982      | 0.164          | 0.829       |
 * | เสียงของกระแทก | "กลับมาที่นี่"                 | -1.065      | 0.021          | 0.837       |
 *
 * `no_speech_prob` ต่ำติดดินทั้งสามอัน (0.02-0.16) ทั้งที่ไม่มีใครพูดสักคำ — มันตอบว่า
 * "มีเสียงพูดแน่นอน" ด้วยความมั่นใจเต็มที่ ใช้เป็นเกณฑ์ไม่ได้เลย ซึ่งขัดกับเกณฑ์มาตรฐาน
 * ที่เอกสาร Whisper แนะนำ (no_speech > 0.6 คู่กับ logprob < -1.0) รอบแรกที่เขียนตามนั้น
 * จึงไม่กรองอะไรออกเลยสักอัน ต้องมาวัดของจริงถึงรู้
 *
 * สองตัวที่แยกออกจริงคือ:
 *   - `avg_logprob` — ความมั่นใจเฉลี่ยต่อคำ เสียงพูดชัดๆ อยู่แถว -0.1 ถึง -0.5
 *     ส่วนคลิปที่มันเดาเอาตกไปที่ -0.98 กับ -1.06
 *   - `compression_ratio` — ข้อความซ้ำตัวเองแค่ไหน คลิปเงียบสนิททำให้มันติดลูป
 *     พ่นคำเดิมซ้ำ ("คือ แม่ง ของเรา คือ แม่ง ของเรา") จนค่าขึ้นไป 2.07
 *
 * ⚠️ ด่านนี้เป็นด่านสำรอง ไม่ใช่ด่านหลัก — คลิปทั้งสามอันข้างบนถูก `useVoiceCall` กัน
 * ไว้ตั้งแต่ในเบราว์เซอร์แล้ว (ไม่ดังพอ หรือดังไม่นานพอ) ไม่มีวันถูกส่งมาถึงที่นี่ด้วยซ้ำ
 * ที่นี่มีไว้รับเคสที่ผ่านด่านแรกมาได้จริง เช่น เครื่องปั่นที่ดังยาวต่อเนื่อง
 * เกณฑ์จึงตั้งแบบระมัดระวัง: ทิ้งคำถามจริงของผู้ใช้แย่กว่าปล่อยให้มโนหลุดมาบ้าง
 * เพราะผู้ใช้ต้องพูดซ้ำโดยไม่รู้ว่าทำไม
 */
function looksHallucinated(text: string, segments: WhisperSegment[]): boolean {
  // พูดวลีเดิมซ้ำ — อาการที่เห็นบ่อยที่สุดเวลามันถอดความเงียบ ("ขอบคุณครับ ขอบคุณครับ",
  // "คือ แม่ง ของเรา คือ แม่ง ของเรา") ต้องเช็คจากข้อความตรงๆ เพราะ `compression_ratio`
  // จับไม่ได้เมื่อข้อความสั้น (สองวลีสั้นๆ ซ้ำกันยังบีบอัดได้ไม่ดีพอที่ค่าจะขึ้นถึงเกณฑ์)
  //
  // ปลอดภัยกับคำถามจริง เพราะคนถามไม่พูดคำเดิมซ้ำครึ่งประโยค และคำถามไทยที่ Whisper
  // ถอดมามักเป็นก้อนเดียวไม่มีช่องว่าง ("ใส่น้ำปลาเท่าไหร่ครับ") ซึ่งไม่เข้าเงื่อนไขนี้เลย
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length >= 2) {
    // วัดเป็น "สัดส่วนตัวอักษรที่อยู่ในคำซ้ำ" ไม่ใช่ "จำนวนคำที่ซ้ำ" — เพราะวลียาวที่ซ้ำ
    // สองครั้งกินเนื้อข้อความเกือบทั้งหมด แต่นับเป็นคำแล้วดูเหมือนซ้ำแค่คำเดียวจากสี่คำ
    // ("ก็คือ แบบนี้ ที่จะเป็นแบบนี้ ที่จะเป็นแบบนี้" — วิธีนับคำมองว่าไม่ซ้ำ ทั้งที่ 73%
    // ของข้อความคือวลีเดิมที่พูดสองรอบ)
    const times = new Map<string, number>();
    for (const word of words) times.set(word, (times.get(word) ?? 0) + 1);
    // นับตัวอักษรของคำที่โผล่มากกว่าหนึ่งครั้ง **ทุกครั้งที่โผล่** ไม่ใช่นับเฉพาะครั้งหลัง —
    // คำถามคือ "ข้อความก้อนนี้เป็นของซ้ำไปกี่ส่วน" ไม่ใช่ "มีส่วนเกินเท่าไหร่"
    const repeatedChars = words.reduce((sum, w) => sum + ((times.get(w) ?? 0) > 1 ? w.length : 0), 0);
    const totalChars = words.reduce((sum, w) => sum + w.length, 0);
    if (totalChars > 0 && repeatedChars / totalChars >= 0.55) return true;
  }

  // มีแต่คำทักทาย/คำลงท้าย ไม่เหลือเนื้อคำถามเลย ("สวัสดีครับ ขอบคุณครับ")
  //
  // เป็นอาการมโนที่พบบ่อยที่สุดของ Whisper กับคลิปเงียบ และเป็นแบบที่เล็ดลอดทั้งกฎ
  // คำซ้ำ (คำไม่ซ้ำกันสักคำ) และเกณฑ์ตัวเลข (มันมั่นใจเต็มที่ว่าได้ยินคำพวกนี้จริง)
  //
  // ทิ้งไปได้โดยไม่เสียอะไร เพราะต่อให้ผู้ใช้พูดว่า "ขอบคุณครับ" จริงๆ ก็ไม่มีคำถามให้เชฟตอบ
  // อยู่ดี — เงียบไว้ดีกว่าตอบทักทายกลับแล้วกินเวลาพูดของสายไปฟรีๆ
  //
  // ⚠️ เกณฑ์ต้องต่ำ (2 ตัวอักษร ไม่ใช่ 4) และห้ามมี "โอเค" อยู่ในรายการที่ตัดทิ้ง
  // เพราะตอนนี้เชฟถามกลับได้แล้วเมื่อฟังคำถามไม่ได้ความ ("หมายถึงอะไรครับ") ผู้ใช้จึง
  // ตอบรับสั้นๆ ในสายจริง — "ใช่ครับ" เหลือเนื้อแค่ "ใช่" 3 ตัวอักษร ถ้าตั้งไว้ที่ 4
  // คำตอบนั้นจะถูกทิ้งเงียบๆ แล้วบทสนทนาค้างอยู่ตรงนั้นโดยผู้ใช้ไม่รู้ว่าทำไม
  //
  // ที่ลดได้โดยไม่เสียการกันมโน เพราะคำทักทายที่ Whisper แต่งขึ้นเอง ("สวัสดีครับ",
  // "ขอบคุณครับ") เหลือเนื้อ 0 ตัวอักษรพอดี ยังเข้าเกณฑ์นี้เต็มๆ อยู่แล้ว
  const meaningful = text.replace(/สวัสดี|ขอบคุณ|ขอบใจ|ครับ|ค่ะ|คะ|จ้า|อือ|เอ่อ|อ่า|ฮะ|นะ|\s/g, '');
  if (meaningful.length < 2) return true;

  const logprob = segments.map(s => s.avg_logprob).filter(n => typeof n === 'number');
  const compression = segments.map(s => s.compression_ratio).filter(n => typeof n === 'number');

  // ไม่มีตัวเลขให้ดูเลย (Groq เปลี่ยนรูปแบบผลลัพธ์ หรือคลิปสั้นจนไม่มีท่อน) —
  // ปล่อยผ่านไปตามเดิม ดีกว่าทิ้งคำถามของผู้ใช้เพราะเราอ่านผลลัพธ์ไม่เป็น
  if (!logprob.length && !compression.length) return false;

  // ติดลูปพ่นคำเดิมซ้ำ — อาการเฉพาะตัวของการถอดความเงียบ ไม่ใช่ของคนถามคำถาม
  if (compression.length && Math.max(...compression) > 2) return true;

  if (!logprob.length) return false;
  const mean = logprob.reduce((a, b) => a + b, 0) / logprob.length;
  // -1.0 คือจุดที่ชั่งน้ำหนักแล้ว ไม่ใช่ -0.9 อย่างที่ตั้งไว้ตอนแรก
  //
  // "ความมั่นใจต่ำ" ไม่ได้แปลว่ามโนเสมอไป — เสียงพูดจริงที่พูดเร็ว เสียงเบา หรือมีเสียง
  // ครัวดังแทรก ก็ได้ค่าต่ำพอๆ กับคลิปที่มันเดาเอา ทั้งสองอย่างทับกันอยู่แถว -0.7 ถึง -1.0
  // เกณฑ์ตรงนี้จึงเลือกไม่ได้ว่าจะถูกทั้งสองทาง ต้องเลือกว่าจะพลาดทางไหน:
  //
  //   ตั้งเข้ม (-0.9) → คำถามจริงถูกทิ้งเงียบๆ ผู้ใช้พูดแล้วไม่มีอะไรเกิดขึ้น และ**ไม่มี
  //                     ทางรู้ว่าทำไม** ต้องเดาเองว่าพูดไม่ชัดหรือแอปพัง
  //   ตั้งผ่อน (-1.0) → ประโยคที่มันเดามาหลุดไปให้เชฟตอบผิดเรื่องบ้าง แต่ผู้ใช้**เห็น
  //                     ซับไตเติล "คุณพูดว่า..."** บนจอ รู้ทันทีว่าถอดผิดแล้วพูดซ้ำได้เลย
  //
  // เลือกทางหลังเพราะความผิดพลาดที่ผู้ใช้มองเห็นและแก้เองได้ ดีกว่าความผิดพลาดที่เงียบ
  // และผ่อนได้เพราะด่านจริงที่กันเสียงรบกวนอยู่ฝั่งเบราว์เซอร์ ส่วนกฎคำซ้ำกับกฎคำทักทาย
  // ล้วนข้างบนไม่ได้อ่อนลงเลย และสองกฎนั้นแทบไม่มีโอกาสตัดคำถามจริงทิ้ง
  return mean < -1;
}

/**
 * ถอดเสียงด้วย Typhoon ASR ของ SCB 10X — โมเดลที่ fine-tune มาสำหรับภาษาไทยโดยเฉพาะ
 *
 * คืน `null` เมื่อเรียกไม่สำเร็จ (ไม่มีคีย์ / เน็ตสะดุด / ชนเพดาน 100 ครั้งต่อนาที)
 * ซึ่งต่างจากการคืนสตริงว่างอย่างสิ้นเชิง — ว่างแปลว่า "ฟังแล้วไม่มีใครพูด" ส่วน null
 * แปลว่า "ไม่ได้ฟัง" ตัวเรียกต้องแยกสองอย่างนี้ให้ออก ไม่งั้นเวลา Typhoon ล่มจะกลายเป็น
 * การทิ้งคำถามของผู้ใช้ทุกประโยค
 *
 * ใช้ fetch ตรงๆ ไม่ผ่าน SDK เพราะ API ของเขาเป็น OpenAI-compatible อยู่แล้ว
 * (ฟิลด์ `file` + `model` แบบ multipart) การลาก SDK อีกตัวเข้ามาเพื่อยิง request เดียว
 * ไม่คุ้มกับ dependency ที่เพิ่ม
 */
async function transcribeWithTyphoon(file: File): Promise<string | null> {
  const key = process.env.TYPHOON_API_KEY;
  if (!key) return null;

  try {
    const form = new FormData();
    form.append('file', file);
    form.append('model', TYPHOON_ASR_MODEL);
    // ⚠️ ไม่ส่ง prompt กับ language ไปด้วย เพราะทดสอบแล้วมันไม่สนใจทั้งคู่ (ผลลัพธ์
    // เหมือนกันเป๊ะทั้งส่งและไม่ส่ง) ส่งไปก็มีแต่ทำให้คนอ่านโค้ดเข้าใจผิดว่ามันใช้งานได้

    // Typhoon เป็นตัวช่วย ไม่ใช่ตัวหลัก จึงต้องไม่มีสิทธิ์ทำให้การถอดเสียงทั้งครั้งค้าง
    //
    // `Promise.all` ที่เรียกฟังก์ชันนี้จะรอจนกว่าทั้งสองเจ้าจะเสร็จ ถ้าฝั่ง Typhoon ค้าง
    // (เน็ตหลุดกลางคัน หรือ API เขามีปัญหา) สายของผู้ใช้จะค้างตามไปด้วยทั้งที่ Whisper
    // ตอบกลับมาเรียบร้อยแล้ว — คนยืนรออยู่หน้าเตาจะเห็นแค่ "กำลังฟังให้ชัด..." ค้างไปเฉยๆ
    //
    // 4 วินาทีเผื่อไว้เยอะแล้วเมื่อเทียบกับที่วัดได้จริง (~0.45 วินาที) หมดเวลาเมื่อไหร่
    // ถือว่า "ไม่ได้ฟัง" แล้วตกไปใช้เกณฑ์สำรอง ไม่ใช่ "ฟังแล้วไม่มีใครพูด"
    const res = await fetch('https://api.opentyphoon.ai/v1/audio/transcriptions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${key}` },
      body: form,
      signal: AbortSignal.timeout(4000),
    });
    if (!res.ok) return null;

    const data = await res.json();
    return typeof data.text === 'string' ? data.text.trim() : null;
  } catch {
    return null;
  }
}

export async function POST(req: NextRequest) {
  try {
    const form = await req.formData().catch(() => null);
    const audio = form?.get('audio');

    if (!form || !(audio instanceof Blob) || audio.size === 0) {
      return NextResponse.json({ error: 'ไม่พบไฟล์เสียง' }, { status: 400 });
    }
    if (audio.size > MAX_AUDIO_BYTES) {
      return NextResponse.json({ error: 'ไฟล์เสียงยาวเกินไป' }, { status: 413 });
    }

    const rawName = form.get('recipeName');
    const recipeName = typeof rawName === 'string' && rawName ? rawName : undefined;

    // ฝั่ง client ส่งมาเป็น JSON array ก้อนเดียว เพื่อไม่ต้องยัด field ซ้ำๆ ใน FormData
    let terms: string[] = [];
    const rawTerms = form.get('terms');
    if (typeof rawTerms === 'string') {
      try {
        const parsed = JSON.parse(rawTerms);
        if (Array.isArray(parsed)) terms = parsed.filter((t): t is string => typeof t === 'string');
      } catch {
        // คำใบ้เป็นของแถมที่ช่วยให้แม่นขึ้น ไม่ใช่ของที่ขาดไม่ได้ —
        // ส่งมาเสียก็ถอดเสียงต่อไปโดยไม่มีคำใบ้ ดีกว่าปฏิเสธทั้งคำถามของผู้ใช้
      }
    }

    // ตั้งชื่อไฟล์ตามชนิดที่เบราว์เซอร์อัดมาจริง — Groq เดาชนิดเสียงจากนามสกุล
    // ถ้าส่งคลิป mp4 จาก iPhone โดยตั้งชื่อ .webm จะโดนปฏิเสธทั้งคลิป
    const mimeType = audio.type || 'audio/webm';
    const file = new File([audio], `speech.${audioExtensionFor(mimeType)}`, { type: mimeType });

    const biasPrompt = buildBiasPrompt(recipeName, terms);

    // ---- ยิงสองเจ้าพร้อมกัน แล้วให้แต่ละเจ้าทำสิ่งที่ตัวเองเก่ง ----
    //
    // Whisper = คนถอดคำ  ·  Typhoon = คนตัดสินว่ามีคนพูดจริงไหม
    //
    // แบ่งหน้าที่แบบนี้เพราะจุดแข็งจุดอ่อนของสองตัวนี้เติมเต็มกันพอดี (วัดจริงมาแล้วทั้งคู่):
    //   - Whisper รับ `prompt` ได้ จึงรู้จักศัพท์ครัวไทยที่เสียงใกล้กัน (กะเพรา/ตะไคร้/ข่า)
    //     แต่มัน**ไม่มีวันตอบว่า "ไม่มีใครพูด"** — เจอคลิปเงียบก็แต่งประโยคขึ้นมาเอง
    //   - Typhoon fine-tune ไทยมาโดยเฉพาะและคืนสตริงว่างตรงๆ เมื่อไม่มีเสียงพูด
    //     แต่ไม่รับ `prompt` จึงไม่มีคำใบ้ศัพท์ครัว
    //
    // ยิงพร้อมกันไม่ใช่ยิงต่อกัน เวลารวมจึงเท่ากับตัวที่ช้ากว่า ไม่ใช่ผลบวก —
    // Typhoon วัดได้ ~0.45 วินาที ส่วน Whisper ~1.9 วินาที แปลว่าด่านกันมโนนี้
    // แทบไม่กินเวลาเพิ่มเลย ซึ่งสำคัญมากเพราะคนยืนรอฟังคำตอบอยู่หน้าเตา
    const [whisperResult, typhoonText] = await Promise.all([
      client.audio.transcriptions.create({
        file,
        model: TRANSCRIBE_MODEL,
        // ล็อกเป็นไทยไปเลย ไม่ปล่อยให้เดาภาษาเอง — คำถามสั้นๆ อย่าง "อันนี้ใช่ไหม"
        // มีเสียงน้อยเกินกว่าจะเดาภาษาถูก แล้วมันจะถอดออกมาเป็นอังกฤษมั่วๆ
        language: 'th',
        prompt: biasPrompt,
        // 0 = ไม่ต้องสร้างสรรค์ งานนี้ต้องการคำที่ได้ยินจริง ไม่ใช่คำที่ฟังดูเข้าท่า
        temperature: 0,
        // ขอแบบ verbose_json ไม่ใช่ json เปล่า เพื่อให้ได้ตัวเลขคุณภาพติดมาด้วย
        // (ดู looksHallucinated) ราคาและความเร็วเท่ากัน ต่างกันแค่ข้อมูลที่แนบกลับมา
        response_format: 'verbose_json',
      }),
      transcribeWithTyphoon(file),
    ]);

    /**
     * ลบตัวอักษรต่างภาษาออกก่อนเป็นอันดับแรก — นี่คือต้นทางของอาการ "เชฟตอบภาษาจีน"
     *
     * Whisper ถูกล็อก `language: 'th'` ไว้แล้ว ตัวอักษรจีน/ญี่ปุ่นที่โผล่มาจึงเป็นความ
     * ผิดพลาดของการถอดเสียงร้อยเปอร์เซ็นต์ ไม่ใช่สิ่งที่ผู้ใช้พูด แต่ข้อความก้อนนั้น
     * จะถูกส่งต่อไปให้เชฟเป็น "คำถามของผู้ใช้" ทันที แล้วเชฟก็ตอบตามภาษาที่เห็น
     *
     * ลบทิ้งแล้วเก็บส่วนที่เป็นไทยไว้ ไม่ทิ้งทั้งประโยค เพราะส่วนใหญ่เป็นคำถามไทยจริงๆ
     * ที่ถอดเพี้ยนไปแค่ไม่กี่ตัว — ทิ้งทั้งก้อนแปลว่าผู้ใช้ต้องพูดซ้ำทั้งที่พูดถูกแล้ว
     */
    const text = stripForeignScript((whisperResult.text ?? '').trim());
    const segments = (whisperResult as { segments?: WhisperSegment[] }).segments ?? [];

    // ด่านทั้งหมดที่แปลว่า "คลิปนี้ไม่มีคำถามของผู้ใช้อยู่"
    //
    // `typhoonText === ''` มาก่อนเกณฑ์เดาสุ่มทั้งหลาย เพราะมันเป็นคำตอบตรงๆ จากโมเดล
    // ที่ฟังคลิปเดียวกันว่าไม่มีเสียงพูด — แม่นกว่าการเดาจากตัวเลขความมั่นใจของ Whisper มาก
    //
    // ส่วน `typhoonText === null` (ไม่มีคีย์ / API ล่ม / ชนเพดาน) ต้องไม่ทำให้ทิ้งคำถาม
    // ทุกประโยค จึงตกไปใช้เกณฑ์เดิมที่จูนไว้แทน — เสียความแม่นไปบ้างแต่สายยังคุยต่อได้
    const reason = !text
      ? 'no-text'
      : typhoonText === ''
        ? 'no-speech'
        : echoesBiasPrompt(text, biasPrompt)
          ? 'bias-echo'
          : looksHallucinated(text, segments)
            ? 'hallucinated'
            : null;

    if (reason) {
      // ไม่ใช่ error — อัดติดแต่ไม่มีเสียงพูด (เสียงกระทะ เสียงพัดลมดูดควัน) เป็นเรื่องปกติ
      // มากในครัว ฝั่ง UI จะวนไปฟังประโยคถัดไปเงียบๆ ไม่ขึ้นว่าระบบพัง
      //
      // ส่ง `reason` กลับไปด้วยเพื่อให้ตามหลังได้ว่าถูกตัดด้วยด่านไหน เวลาต้องมาจูน
      // เกณฑ์ใหม่หลังลองใช้จริงในครัว — ไม่งั้นจะเห็นแค่ "เงียบไป" แล้วเดาไม่ออกว่าเพราะอะไร
      return NextResponse.json({ text: '', empty: true, reason });
    }

    return NextResponse.json({ text });
  } catch (error) {
    console.error('Transcribe error:', error);
    return NextResponse.json({ error: 'ถอดเสียงไม่สำเร็จ' }, { status: 500 });
  }
}
