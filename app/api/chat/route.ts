    // ⚠️ ต้อง stripMarkdown **ก่อน** ตรวจภาษาเสมอ ห้ามสลับลำดับ
    //
    // stripMarkdown แปลงเครื่องหมายวรรคตอนแบบเต็มความกว้าง (？ ！ ，) เป็นแบบปกติให้อยู่แล้ว
    // ถ้าตรวจภาษาก่อน คำตอบไทยที่สมบูรณ์ทุกอย่างแต่ลงท้ายด้วย ？ ตัวเดียว (ซึ่งโมเดลตัวนี้
    // ทำบ่อย) จะถูกตีว่า "หลุดภาษา" แล้วยิงซ้ำอีกสองรอบฟรีๆ กินเวลาราว 4 วินาทีกลางสาย
    // ทั้งที่เป็นปัญหาที่แก้ได้ด้วยการแทนที่ตัวอักษรตัวเดียว ไม่ต้องถามโมเดลใหม่เลย
    let text = stripMarkdown(await ask(0.4));

    // คำตอบหลุดไปเป็นภาษาอื่น — ยิงซ้ำด้วยอุณหภูมิที่ต่ำลงมาก พร้อมบอกไปตรงๆ ว่า
    // รอบที่แล้วผิดกฎข้อไหน (การชี้ความผิดของจริงได้ผลกว่าการย้ำกฎลอยๆ ตั้งแต่รอบแรก)
    //
    // ในโหมดโทรคุยเรื่องนี้แย่เป็นพิเศษ เพราะเครื่องจะ**อ่านออกเสียงภาษาจีนนั้นใส่หูผู้ใช้**
    // ที่กำลังยืนทำอาหารอยู่ ไม่ใช่แค่ข้อความแปลกๆ บนจอที่กวาดตาข้ามได้
