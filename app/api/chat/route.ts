import Groq from 'groq-sdk';
import { NextRequest, NextResponse } from 'next/server';
import { TEXT_MODEL } from '@/lib/groq';
import { buildDietPromptRules, sanitizeDietInput } from '@/lib/diet';

const client = new Groq({ apiKey: process.env.GROQ_API_KEY });

/**
 * ล้างสัญลักษณ์ Markdown กับขีดกลางแบบพิเศษออกจากคำตอบของเชฟ
 *
 * กล่องแชทใน `ChefChat.tsx` แสดงข้อความดิบตามที่ส่งมาตรงๆ (ไม่ได้ render Markdown)
 * ถ้ามี ** หรือ - นำหน้าบรรทัดหลุดมา ผู้ใช้จะเห็นเครื่องหมายพวกนี้โผล่กลางคำตอบ
 *
 * สั่งห้ามไว้ใน system prompt แล้ว แต่กรองซ้ำฝั่ง server ตามหลักเดียวกับที่ใช้กับ
 * เมนูซ้ำและเครื่องปรุงพื้นฐาน: สั่ง AI อย่างเดียวไม่พอ ต้องตรวจผลลัพธ์ก่อนถึงจอด้วย
 * (โมเดล gpt-oss ยังใส่ขีดกลางแบบ non-breaking (U+2011) มาอยู่ดีแม้สั่งห้ามแล้ว)
 */
function stripMarkdown(text: string): string {
  return text
    // ตัวหนา/ตัวเอียง — เก็บข้อความข้างในไว้ ตัดเฉพาะเครื่องหมาย
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/(^|\s)\*([^*\n]+)\*(?=\s|$)/g, '$1$2')
    // หัวข้อ ## และ bullet ที่ขึ้นต้นบรรทัด (ทั้ง - * และ •)
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/^\s*[-*•]\s+/gm, '')
    // ขีดกลางแบบพิเศษที่อ่านยากบนมือถือบางรุ่น → ขีดปกติ
    .replace(/[‐‑‒–—]/g, '-')
    .trim();
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => null);
    if (!body || !body.messages) {
      return NextResponse.json({ error: 'Missing messages' }, { status: 400 });
    }

    const { messages, recipeName, recipeSteps, ingredients, servings, recipeIngredients, currentStep, voice } = body;

    // คำตอบนี้กำลังจะถูกอ่านออกเสียง ไม่ใช่อ่านด้วยตา — คนละข้อจำกัดกันคนละเรื่อง
    //
    // ข้อความ 4 ประโยคที่กวาดตาอ่านบนจอจบใน 3 วินาที ใช้เวลาฟังเกินครึ่งนาที และคนฟัง
    // ย้อนกลับไปอ่านซ้ำท่อนที่หลุดไม่ได้เหมือนตอนอ่านบนจอ ต้องจำให้ได้ตั้งแต่รอบแรก
    // ที่ได้ยิน คำตอบสำหรับหูจึงต้องสั้นกว่าและเรียงลำดับต่างออกไป: ตอบก่อน อธิบายทีหลัง
    const voiceRules = voice
      ? `ตอนนี้ผู้ใช้คุยด้วยเสียง และคำตอบของคุณจะถูกอ่านออกเสียงให้ฟัง ไม่ได้อ่านด้วยตา:
                  - สั้นกว่าปกติอีก ไม่เกิน 2 ประโยค ตอบเฉพาะสิ่งที่ถาม ไม่ต้องเกริ่นนำและไม่ต้องสรุปท้าย
                  - ขึ้นต้นด้วยคำตอบเลย เพราะคนฟังรอทั้งประโยคกว่าจะรู้คำตอบไม่ได้ ("ใช้โหระพาแทนได้ครับ แต่กลิ่นจะหวานกว่า" ไม่ใช่ "เรื่องการแทนวัตถุดิบนั้น...")
                  - ห้ามตอบเป็นข้อ 1 2 3 เพราะฟังแล้วแยกไม่ออกว่าข้อไหนจบตรงไหน ถ้ามีหลายอย่างให้พูดต่อกันด้วยคำว่า "แล้วก็" หรือ "จากนั้น"
                  - เขียนหน่วยเป็นคำเต็มอย่างที่คนพูดกัน ("สองช้อนโต๊ะ" ไม่ใช่ "2 ช้อนโต๊ะ", "หนึ่งร้อยห้าสิบกรัม" ไม่ใช่ "150 g")
                  - ห้ามใช้วงเล็บและห้ามใช้เครื่องหมายคำพูด เพราะเครื่องอ่านออกเสียงข้ามให้เฉยๆ จนความหมายเพี้ยน`
      : '';

    // ข้อจำกัดด้านอาหารต้องมาถึงเชฟด้วย ไม่งั้นคำถามยอดฮิต "ไม่มีน้ำปลาใช้อะไรแทน"
    // จะได้คำตอบว่า "ใช้ซอสหอยนางรมแทน" ให้คนกินมังสวิรัติ
    const { restrictions, allergies } = sanitizeDietInput(body.dietRestrictions, body.allergies);
    const dietRules = buildDietPromptRules(restrictions, allergies);

    // ปริมาณที่ผู้ใช้เห็นอยู่บนจอ ณ ตอนถาม (ปรับตามจำนวนคนที่เขาเลือกไว้แล้ว)
    // ต้องบอกเชฟด้วย ไม่งั้นคำถามยอดฮิต "ทำให้กิน 3 คนต้องเพิ่มของเท่าไหร่" จะได้คำตอบวนเปล่าๆ
    const servingsContext =
      typeof servings === 'number' && servings > 0
        ? `ปริมาณวัตถุดิบที่ผู้ใช้เห็นอยู่ตอนนี้คือสูตรที่ปรับให้ทำกิน ${servings} คนแล้ว${
            Array.isArray(recipeIngredients) && recipeIngredients.length
              ? `: ${recipeIngredients.join(', ')}`
              : ''
          }
                  ถ้าผู้ใช้ถามเรื่องจำนวนคนกินหรือปริมาณ ให้ตอบเป็นตัวเลขจริงจากรายการนี้ ห้ามตอบแบบวนกลับว่า "คูณเท่าตัวจากสูตรสำหรับ 1 คน"
                  และบอกด้วยว่าเขากดปุ่ม + / - ที่หัวข้อวัตถุดิบเพื่อให้แอปคิดปริมาณให้ใหม่ได้เลย`
        : '';

    // ผู้ใช้เปิดแชทตอนอยู่ในโหมดทำอาหาร = กำลังยืนอยู่หน้าเตาที่ขั้นตอนใดขั้นตอนหนึ่ง
    // บอกเชฟไปด้วยว่าอยู่ขั้นไหน จะได้ตอบตรงจุดโดยผู้ใช้ไม่ต้องพิมพ์อธิบายเองว่า "ตอนนี้ทำถึงข้อ 3"
    const stepContext =
      currentStep && typeof currentStep.number === 'number'
        ? `ตอนนี้ผู้ใช้กำลังทำขั้นตอนที่ ${currentStep.number} จากทั้งหมด ${currentStep.total} ขั้น: "${currentStep.text}"
                  ถ้าผู้ใช้ถามลอยๆ เช่น "แบบนี้ใช่ไหม" "นานแค่ไหน" ให้ตีความว่าหมายถึงขั้นตอนนี้`
        : '';

    const response = await client.chat.completions.create({
      model: TEXT_MODEL,
      temperature: 0.4, // ลดจาก default เพื่อลดโอกาสที่โมเดลจะแทรกคำ/ตัวอักษรภาษาอื่นปนกลางประโยคไทย
      // gpt-oss เป็น reasoning model — ต้องกันเผื่อ token ที่มันใช้ "คิดก่อนตอบ" ไม่งั้นคำตอบถูกตัดกลางประโยค
      // หน้านี้เป็นบทสนทนาสั้นๆ ข้างเตา ไม่ต้องเผื่อเท่าอีก 2 route ที่ตอบเป็น JSON ก้อนใหญ่
      max_completion_tokens: 1500,
      // คนยืนถือตะหลิวรออยู่ ตอบเร็วสำคัญกว่าตอบลึก
      reasoning_effort: 'low',
      messages: [
        {
          role: 'system',
          content: `คุณคือ "Executive Chef de Cuisine" ผู้เชี่ยวชาญด้านอาหารและโภชนาการ
                  บุคลิก: รอบรู้, ช่างสังเกต, ให้คำแนะนำที่ใช้งานได้จริง, เป็นมิตรแต่เป็นมืออาชีพ
                  ตอนนี้ผู้ใช้กำลังทำเมนู: ${recipeName || 'อาหารทั่วไป'}
                  วิธีทำ: ${recipeSteps?.join(' | ') || 'ไม่ได้ระบุ'}
                  วัตถุดิบที่ผู้ใช้มีอยู่ในตู้เย็นตอนนี้: ${ingredients?.length ? ingredients.join(', ') : 'ไม่ได้ระบุ'}
                  ${servingsContext}
                  ${stepContext}
                  ${dietRules}
                  ${voiceRules}
                  ถ้าผู้ใช้ถามเรื่องการแทนวัตถุดิบ ให้เช็คก่อนว่ามีอะไรในลิสต์ข้างต้นที่เอามาแทนได้ไหม แล้วแนะนำอันนั้นก่อน ก่อนจะแนะนำให้ไปซื้อของใหม่ และของที่แนะนำต้องไม่ผิดข้อจำกัดด้านอาหารข้างต้นเด็ดขาด
                  กฎสำคัญ:
                  - ตอบเป็นภาษาไทยล้วนทั้งหมด ห้ามมีคำหรือตัวอักษรภาษาอื่น (อังกฤษ จีน เวียดนาม ฯลฯ) ปนกลางประโยคเด็ดขาด ยกเว้นชื่อเฉพาะที่ไม่มีคำแปลไทยจริงๆ เท่านั้น
                  - ให้คำแนะนำที่ชัดเจนและแม่นยำ (Professional & Precise)
                  - หากมีการเปลี่ยนวัตถุดิบ ให้เน้นความปลอดภัยของอาหาร (Food Safety First)
                  - ตอบสั้น กระชับ ไม่เวิ่นเว้อ ปกติไม่ควรเกิน 3-4 ประโยค เพราะผู้ใช้ถืออุปกรณ์ทำครัวอยู่หน้าเตา อ่านยาวๆ ไม่ไหว
                  - **ตอบเป็นข้อความธรรมดาเท่านั้น ห้ามใช้ Markdown เด็ดขาด** — ห้ามใช้ ** ทำตัวหนา, ห้าม # หัวข้อ, ห้ามขึ้นต้นบรรทัดด้วย - หรือ * เป็น bullet, ห้ามตาราง เพราะหน้าจอแชทแสดงข้อความดิบตามที่ส่งมาตรงๆ ไม่ได้แปลง Markdown ถ้าใส่มาผู้ใช้จะเห็นเครื่องหมายพวกนี้โผล่กลางคำตอบ
                  - ถ้าต้องบอกหลายข้อ ให้เขียนต่อกันเป็นประโยคหรือขึ้นบรรทัดใหม่เฉยๆ โดยไม่ต้องมีสัญลักษณ์นำหน้า
                  - ห้ามใช้ขีดกลางแบบพิเศษ (เช่น ‑ – —) ให้ใช้ขีดปกติหรือเว้นวรรคแทน`,
        },
        ...messages.map((m: { role: string; content: string }) => ({
          role: m.role === 'assistant' ? 'assistant' : 'user',
          content: m.content,
        })),
      ],
    });

    const text = response.choices[0]?.message?.content || 'ขอโทษครับ ลองถามใหม่อีกครั้ง';
    return NextResponse.json({ role: 'assistant', content: stripMarkdown(text) });
  } catch (error) {
    console.error('Chat error:', error);
    return NextResponse.json(
      { role: 'assistant', content: 'เกิดข้อผิดพลาดในการเชื่อมต่อกับเชฟ' }, 
      { status: 500 }
    );
  }
}
